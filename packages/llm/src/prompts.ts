/** Складає блок контексту з ретрівнутих чанків, нумеруючи джерела для цитат [n]. */
export function buildContextBlock(chunks: RetrievedChunk[]): string {
  return chunks
    .map((c, i) => `[${i + 1}] (товар ${c.productId}, тип: ${c.chunkType})\n${c.text}\nДжерело: ${c.sourceUrls[0] ?? "—"}`)
    .join("\n\n");
}

export function buildAnswerMessages(query: string, chunks: RetrievedChunk[]) {
  return [
    { role: "system" as const, content: SYSTEM_ANSWER },
    {
      role: "user" as const,
      content: `КОНТЕКСТ:\n${buildContextBlock(chunks)}\n\nПИТАННЯ: ${query}\n\nВідповідь (з маркерами [n]):`,
    },
  ];
}
