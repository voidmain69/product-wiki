/**
 * Складає блок контексту, нумеруючи фрагменти [1], [2]… для цитат. Внутрішні поля
 * (productId/chunkType) НЕ показуємо моделі — слабші моделі копіювали цей службовий
 * заголовок у відповідь. Модель бачить лише номер, текст і джерело.
 */
export function buildContextBlock(chunks: RetrievedChunk[]): string {
  return chunks
    .map((c, i) => `[${i + 1}] ${c.text}\nДжерело: ${c.sourceUrls[0] ?? "—"}`)
    .join("\n\n");
}

export function buildAnswerMessages(query: string, chunks: RetrievedChunk[]) {
  return [
    { role: "system" as const, content: SYSTEM_ANSWER },
    {
      role: "user" as const,
      // Хвіст праймить НОМЕРНІ маркери (не літеральне «[n]», яке слабші моделі копіювали).
      content: `КОНТЕКСТ:\n${buildContextBlock(chunks)}\n\nПИТАННЯ: ${query}\n\nВідповідь українською, з номерними маркерами джерел (наприклад [1], [2]):`,
    },
  ];
}
